/* ==========================================================================
   Renders Telegram channel-post comment threads into the page.
   Do not edit this file to set up the forum - edit assets/config.js.

   How it works
   ------------
   Telegram serves an official "discussion" widget: a script tag carrying
   data-telegram-discussion="<channel>/<post>" replaces itself with an iframe
   showing that post's comment thread. Reading needs no Telegram account,
   because a public channel is publicly readable. Posting uses Telegram.

   Usage in a page:
     <div data-forum-thread="lpm-logit-probit"></div>
     <script src="assets/config.js"></script>
     <script src="assets/forum.js"></script>
   ========================================================================== */

(function () {
  "use strict";

  var WIDGET_SRC = "https://telegram.org/js/telegram-widget.js?22";

  var cfg = window.FORUM_CONFIG || {};
  var channel = (cfg.channel || "").replace(/^@/, "").trim();
  var threads = cfg.threads || [];

  function findThread(slug) {
    for (var i = 0; i < threads.length; i++) {
      if (threads[i].slug === slug) return threads[i];
    }
    return null;
  }

  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text) n.textContent = text;
    return n;
  }

  function groupHref() {
    if (cfg.groupLink) return cfg.groupLink;
    if (channel) return "https://t.me/" + channel;
    return null;
  }

  /* The "nothing to show yet" state. Deliberately explicit, so an
     unconfigured page explains itself instead of looking broken. */
  function renderNotice(box, thread, slug) {
    var n = el("div", "notice");
    var html;
    if (!channel) {
      html = "<strong>Forum belum aktif.</strong> Kanal Telegram belum diisi. " +
             "Buka <code>assets/config.js</code> dan tulis nama kanal pada " +
             "<code>channel</code>.";
    } else if (!thread) {
      html = "<strong>Thread <code>" + escapeHtml(slug) + "</code> belum terdaftar.</strong> " +
             "Tambahkan entri dengan <code>slug</code> tersebut di <code>assets/config.js</code>.";
    } else {
      html = "<strong>Thread ini belum dibuka.</strong> Kirim satu pos di kanal " +
             "<code>@" + escapeHtml(channel) + "</code> untuk topik ini, lalu tulis nomor " +
             "posnya pada <code>post</code> di <code>assets/config.js</code>.";
    }
    n.innerHTML = html;
    box.appendChild(n);
  }

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  /* Inject the Telegram widget script. It replaces itself with an iframe at
     the position where it sits, so it is appended inside the frame div. */
  function renderWidget(frame, post) {
    var s = document.createElement("script");
    s.async = true;
    s.src = WIDGET_SRC;
    s.setAttribute("data-telegram-discussion", channel + "/" + post);
    s.setAttribute("data-comments-limit", String(cfg.commentsLimit || 20));
    if (cfg.colorful) s.setAttribute("data-colorful", "1");
    s.setAttribute("data-dark", prefersDark() ? "1" : "0");
    frame.appendChild(s);
  }

  function prefersDark() {
    return !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
  }

  function renderOne(box) {
    var slug = box.getAttribute("data-forum-thread");
    var thread = findThread(slug);
    var showChrome = box.getAttribute("data-forum-chrome") !== "off";

    if (showChrome && thread) {
      box.appendChild(el("h3", null, thread.title));
      if (thread.note) box.appendChild(el("p", "intro", thread.note));
    }

    if (!channel || !thread || !thread.post) {
      renderNotice(box, thread, slug);
      return;
    }

    var frame = el("div", "frame");
    box.appendChild(frame);
    renderWidget(frame, thread.post);

    /* Always offer the direct route as well. If the widget is blocked, or a
       student would rather use the app, the thread is still one tap away. */
    var actions = el("p");
    actions.style.margin = "1rem 0 0";
    var a = el("a", "btn", "Buka thread di Telegram");
    a.href = "https://t.me/" + channel + "/" + thread.post;
    a.target = "_blank";
    a.rel = "noopener";
    actions.appendChild(a);

    var g = groupHref();
    if (g) {
      var b = el("a", "btn ghost", "Gabung grup diskusi");
      b.href = g;
      b.target = "_blank";
      b.rel = "noopener";
      actions.appendChild(b);
    }
    box.appendChild(actions);
  }

  function boot() {
    var boxes = document.querySelectorAll("[data-forum-thread]");
    for (var i = 0; i < boxes.length; i++) renderOne(boxes[i]);

    /* Fill any element marked data-forum-index with the thread list. */
    var idx = document.querySelectorAll("[data-forum-index]");
    for (var j = 0; j < idx.length; j++) renderIndex(idx[j]);
  }

  function renderIndex(target) {
    var accents = ["var(--terra)", "var(--indigo)", "var(--sage)", "var(--ochre)"];
    var ol = el("ol", "list");
    threads.forEach(function (t, i) {
      var live = channel && t.post;
      var li = el("li", "card" + (live ? "" : " tbd"));
      li.style.setProperty("--accent", accents[i % accents.length]);

      var hit = document.createElement(live ? "a" : "div");
      hit.className = "hit";
      if (live) {
        hit.href = "https://t.me/" + channel + "/" + t.post;
        hit.target = "_blank";
        hit.rel = "noopener";
      }
      hit.appendChild(el("span", "num", String(i + 1)));
      hit.appendChild(el("h3", null, t.title));
      var m = el("p", "meta");
      m.appendChild(el("span", null, live ? "terbuka" : "belum dibuka"));
      if (t.note) m.appendChild(el("span", null, t.note));
      hit.appendChild(m);
      li.appendChild(hit);
      ol.appendChild(li);
    });
    target.appendChild(ol);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
})();
